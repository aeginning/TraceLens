import json
import math
from pathlib import Path

from PIL import Image, ImageDraw


ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / "app" / "src" / "main" / "assets" / "starter_patterns"
IMAGES = CATALOG / "images"
SIZE = 900
PURPLE = (80, 48, 130, 255)
WIDTH = 22


def canvas():
    image = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    return image, ImageDraw.Draw(image)


def star():
    image, draw = canvas()
    points = []
    for point in range(10):
        radius = SIZE * (0.38 if point % 2 == 0 else 0.16)
        angle = -math.pi / 2 + point * math.pi / 5
        points.append((SIZE / 2 + math.cos(angle) * radius, SIZE / 2 + math.sin(angle) * radius))
    draw.line(points + [points[0]], fill=PURPLE, width=WIDTH, joint="curve")
    return image


def heart():
    image, draw = canvas()
    points = []
    for step in range(361):
        t = step * 2 * math.pi / 360
        x = 16 * math.sin(t) ** 3
        y = 13 * math.cos(t) - 5 * math.cos(2 * t) - 2 * math.cos(3 * t) - math.cos(4 * t)
        points.append((SIZE / 2 + x * 19, SIZE / 2 - y * 19 + 20))
    draw.line(points, fill=PURPLE, width=WIDTH, joint="curve")
    return image


def flower():
    image, draw = canvas()
    center = SIZE / 2
    for petal in range(8):
        angle = petal * math.pi / 4
        x = center + math.cos(angle) * SIZE * 0.22
        y = center + math.sin(angle) * SIZE * 0.22
        draw.ellipse(
            (x - SIZE * 0.12, y - SIZE * 0.18, x + SIZE * 0.12, y + SIZE * 0.18),
            outline=PURPLE,
            width=WIDTH,
        )
    draw.ellipse(
        (center - SIZE * 0.13, center - SIZE * 0.13, center + SIZE * 0.13, center + SIZE * 0.13),
        outline=PURPLE,
        width=WIDTH,
    )
    draw.line((center, SIZE * 0.63, center, SIZE * 0.88), fill=PURPLE, width=WIDTH)
    draw.ellipse((SIZE * 0.5, SIZE * 0.72, SIZE * 0.72, SIZE * 0.84), outline=PURPLE, width=WIDTH)
    return image


def butterfly():
    image, draw = canvas()
    left = [(430, 430), (320, 120), (90, 170), (180, 440), (60, 620), (300, 770), (430, 520)]
    right = [(SIZE - x, y) for x, y in left]
    draw.line(left, fill=PURPLE, width=WIDTH, joint="curve")
    draw.line(right, fill=PURPLE, width=WIDTH, joint="curve")
    draw.ellipse((420, 300, 480, 680), outline=PURPLE, width=WIDTH)
    draw.line((440, 320, 350, 190), fill=PURPLE, width=WIDTH)
    draw.line((460, 320, 550, 190), fill=PURPLE, width=WIDTH)
    return image


PATTERNS = [
    ("star", "Star", "Gwiazda", star),
    ("heart", "Heart", "Serce", heart),
    ("flower", "Flower", "Kwiat", flower),
    ("butterfly", "Butterfly", "Motyl", butterfly),
]


def main():
    IMAGES.mkdir(parents=True, exist_ok=True)
    entries = []
    for pattern_id, name_en, name_pl, factory in PATTERNS:
        factory().save(IMAGES / f"{pattern_id}.png", optimize=True)
        entries.append(
            {
                "id": pattern_id,
                "file": f"images/{pattern_id}.png",
                "name": {"en": name_en, "pl": name_pl},
                "author": "TraceLens",
                "license": "OWN_WORK",
                "source": "TraceLens source code",
                "model": "",
                "prompt": "",
                "licenseNotes": "Original geometric pattern generated by the TraceLens project.",
            }
        )
    (CATALOG / "manifest.json").write_text(
        json.dumps({"schemaVersion": 1, "patterns": entries}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
